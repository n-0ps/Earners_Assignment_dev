

let num;
num = 3;

// Positive, Negative or Zero

if(num>0){
    console.log("Positive Number");
}
else if(num<0){
    console.log("Negative Number");
}
else if(num=0){
    console.log("Zero");
}


// Even or Odd

if(num%2 == 0){
    console.log("Even Number");
}
if(num%2 != 0){
    console.log("Odd Number");
}


